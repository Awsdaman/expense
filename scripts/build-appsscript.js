// Concatenates the pure modules in src/ into one classic script for Apps Script,
// which has a single global scope and no module system.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'apps-script/lib/Lib.js');

// Dependency order: a top-level const may reference consts from earlier files.
const FILES = [
  'src/parser/normalize.js',
  'src/parser/amount.js',
  'src/parser/dates.js',
  'src/parser/merchant.js',
  'src/parser/redact.js',
  'src/parser/ignore.js',
  'src/parser/banks/barq.js',
  'src/parser/banks/alrajhi.js',
  'src/parser/banks/snb.js',
  'src/parser/index.js',
  'src/core/settings.js',
  'src/core/format.js',
  'src/core/cycle.js',
  'src/core/hash.js',
  'src/core/rules.js',
  'src/core/summary.js',
  'src/core/report.js',
  'src/core/api.js',
];

const seen = new Map();
const parts = ['// Generated by scripts/build-appsscript.js. Do not edit; change src/ instead.\n'];

for (const file of FILES) {
  const src = readFileSync(join(root, file), 'utf8');
  if (/^\s*export\s+(default|\{|\*)/m.test(src)) {
    throw new Error(`${file}: only named "export function" / "export const" are supported`);
  }
  for (const [, name] of src.matchAll(/^(?:export\s+)?(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    if (seen.has(name)) throw new Error(`Duplicate top-level name "${name}" in ${file} and ${seen.get(name)}`);
    seen.set(name, file);
  }
  const body = src
    .replace(/^import\s[^\n]*\n/gm, '')
    .replace(/^export\s+/gm, '');
  parts.push(`// ---- ${file}\n${body.trim()}\n`);
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, parts.join('\n'));
console.log(`Wrote ${out} (${FILES.length} files, ${seen.size} top-level names)`);
